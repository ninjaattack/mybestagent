// Код страны из заявки: две латинские буквы; RU и пусто — Россия (хранится пустой строкой)
function normCountry(v) {
  const c = String(v || '').trim().toUpperCase();
  if (!/^[A-Z]{2}$/.test(c) || c === 'RU') return '';
  return c;
}
const countryName = (code, lang = 'ru') => { const c = BY_CODE.get(code); return c ? c[lang === 'en' ? 'en' : 'ru'] : code; };

